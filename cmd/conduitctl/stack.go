package main

import (
	"bytes"
	"crypto/rand"
	"encoding/hex"
	"errors"
	"fmt"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path/filepath"
	"strconv"
	"strings"
	"time"

	"github.com/tjscanlan/conduit/deployments/quickstart"
	"github.com/tjscanlan/conduit/internal/devpki"
)

// projectName matches compose.yml's name, so `docker compose -p
// conduit-quickstart ...` reaches the stack however it was started.
const projectName = "conduit-quickstart"

type stack struct {
	dir         string
	uiPort      int
	gatewayPort int
	images      string
	noDemo      bool
	out         io.Writer
}

func (s *stack) certDir() string { return filepath.Join(s.dir, ".conduit", "certs") }

// writeBundle refreshes the embedded compose files in s.dir; credentials
// (.env and .conduit/) are left alone.
func (s *stack) writeBundle() error {
	return fs.WalkDir(quickstart.Bundle, ".", func(path string, d fs.DirEntry, err error) error {
		if err != nil {
			return err
		}
		dst := filepath.Join(s.dir, path)
		if d.IsDir() {
			return os.MkdirAll(dst, 0o755)
		}
		b, err := quickstart.Bundle.ReadFile(path)
		if err != nil {
			return err
		}
		return os.WriteFile(dst, b, 0o644)
	})
}

// writeEnv creates the stack's secrets once (owner-only).
func (s *stack) writeEnv() error {
	path := filepath.Join(s.dir, ".env")
	if _, err := os.Stat(path); err == nil {
		return nil
	}
	hexKey := func(n int) string {
		b := make([]byte, n)
		_, _ = rand.Read(b)
		return hex.EncodeToString(b)
	}
	content := fmt.Sprintf("# Generated by conduitctl. Delete with 'conduitctl reset'.\nCLICKHOUSE_PASSWORD=%s\nUI_SESSION_KEY=%s\n", hexKey(24), hexKey(32))
	return os.WriteFile(path, []byte(content), 0o600)
}

func (s *stack) compose(args ...string) *exec.Cmd {
	full := append([]string{"compose", "--project-directory", s.dir, "-f", filepath.Join(s.dir, "compose.yml"), "-p", projectName}, args...)
	cmd := exec.Command("docker", full...)
	cmd.Env = append(os.Environ(),
		"CONDUIT_VERSION="+s.images,
		"CONDUIT_UI_PORT="+strconv.Itoa(s.uiPort),
		"CONDUIT_GATEWAY_PORT="+strconv.Itoa(s.gatewayPort),
		"CONDUIT_UID="+strconv.Itoa(os.Getuid()),
		"CONDUIT_GID="+strconv.Itoa(os.Getgid()),
	)
	cmd.Stdout, cmd.Stderr = s.out, os.Stderr
	return cmd
}

func (s *stack) say(format string, a ...any) { fmt.Fprintf(s.out, "==> "+format+"\n", a...) }

func (s *stack) checkImages() error {
	if s.images == "dev" {
		return errors.New("this is a development build of conduitctl, so it has no matching images: " +
			"pass -images vX.Y.Z (a release that publishes conduit-init and conduit-demo-agent), " +
			"or run deployments/quickstart/quickstart.sh from a checkout")
	}
	return nil
}

func (s *stack) up() error {
	if err := preflight(); err != nil {
		return err
	}
	if err := s.checkImages(); err != nil {
		return err
	}
	start := time.Now()
	if err := os.MkdirAll(filepath.Join(s.dir, ".conduit"), 0o700); err != nil {
		return err
	}
	if err := s.writeBundle(); err != nil {
		return fmt.Errorf("write compose bundle: %w", err)
	}
	if err := s.writeEnv(); err != nil {
		return err
	}
	s.say("Starting Conduit %s in %s", s.images, s.dir)
	args := []string{"up", "-d", "--wait", "--wait-timeout", "300"}
	if s.noDemo {
		args = append(args, "--scale", "demo-agent=0")
	}
	if err := s.compose(args...).Run(); err != nil {
		_ = s.compose("ps", "-a").Run()
		if home, _ := os.UserHomeDir(); home != "" && !strings.HasPrefix(s.dir, home+string(filepath.Separator)) {
			return fmt.Errorf("the stack did not become healthy. %s is outside your home directory, and Docker Desktop "+
				"and Colima share only some host folders (usually your home) with containers; use a -dir under %s", s.dir, home)
		}
		return fmt.Errorf("the stack did not become healthy; run `conduitctl doctor` to see why")
	}
	s.say("Stack is healthy after %s", time.Since(start).Round(time.Second))
	if !s.noDemo {
		deadline := time.Now().Add(90 * time.Second)
		for !s.demoTraceSeen() {
			if time.Now().After(deadline) {
				return errors.New("no trace from demo-agent after 90s; run `conduitctl doctor`")
			}
			time.Sleep(time.Second)
		}
		s.say("Traces from demo-agent are arriving (%s after start)", time.Since(start).Round(time.Second))
	}
	s.banner()
	return nil
}

// demoTraceSeen asks ClickHouse, inside its container, for demo-agent spans.
func (s *stack) demoTraceSeen() bool {
	cmd := s.compose("exec", "-T", "clickhouse", "sh", "-c",
		`clickhouse-client --user obs --password "$CLICKHOUSE_PASSWORD" --database observability -q "SELECT count() FROM spans WHERE agent_name = 'demo-agent'"`)
	var buf bytes.Buffer
	cmd.Stdout, cmd.Stderr = &buf, io.Discard
	if err := cmd.Run(); err != nil {
		return false
	}
	n := strings.TrimSpace(buf.String())
	return n != "" && n != "0"
}

func (s *stack) login() (user, pass string) {
	b, err := os.ReadFile(filepath.Join(s.dir, ".conduit", "ui-login.txt"))
	if err != nil {
		return "?", "(missing: run `conduitctl reset`, then quickstart)"
	}
	user, pass, _ = strings.Cut(strings.TrimSpace(string(b)), " ")
	return user, pass
}

func (s *stack) banner() {
	user, pass := s.login()
	fmt.Fprintf(s.out, `
Conduit is running.

  UI        http://localhost:%d
  Login     %s / %s
  Gateway   localhost:%d (mTLS)

Send a trace from your agent as "my-agent":

  export CONDUIT_GATEWAY_ADDR=localhost:%d
  export CONDUIT_CERT_DIR=%s
  export CONDUIT_AGENT=my-agent

  Python:  pip install conduit-observability, then: conduit.configure()
  Go:      go get github.com/tjscanlan/conduit/sdk/go, then: sdk.NewFromEnv()

Another agent: conduitctl agent-cert NAME    Problems: conduitctl doctor
Docs: https://tjscanlan.github.io/conduit/   Stop: conduitctl down
`, s.uiPort, user, pass, s.gatewayPort, s.gatewayPort, s.certDir())
}

func (s *stack) status() error {
	if err := preflight(); err != nil {
		return err
	}
	if err := s.compose("ps").Run(); err != nil {
		return err
	}
	s.banner()
	return nil
}

func (s *stack) down() error {
	if err := preflight(); err != nil {
		return err
	}
	if err := s.compose("down").Run(); err != nil {
		return err
	}
	s.say("Stopped. Data and credentials are kept; `conduitctl quickstart` starts it again.")
	return nil
}

func (s *stack) reset() error {
	if err := preflight(); err != nil {
		return err
	}
	if _, err := os.Stat(filepath.Join(s.dir, "compose.yml")); err == nil {
		if err := s.compose("down", "-v", "--remove-orphans").Run(); err != nil {
			return err
		}
	}
	for _, p := range []string{".conduit", ".env"} {
		if err := os.RemoveAll(filepath.Join(s.dir, p)); err != nil {
			return err
		}
	}
	s.say("Deleted all quickstart data and credentials in %s.", s.dir)
	return nil
}

func (s *stack) agentCert(name string) error {
	crt, key, created, err := devpki.IssueAgent(filepath.Join(s.dir, ".conduit"), name)
	if err != nil {
		return err
	}
	if created {
		s.say("Issued a certificate for agent %q", name)
	} else {
		s.say("Agent %q already has a valid certificate", name)
	}
	fmt.Fprintf(s.out, "\n  certificate  %s\n  key          %s\n\nUse it:\n\n  export CONDUIT_CERT_DIR=%s CONDUIT_AGENT=%s\n",
		crt, key, s.certDir(), name)
	return nil
}

func preflight() error {
	if _, err := exec.LookPath("docker"); err != nil {
		return errors.New("Docker is not installed: get it from https://docs.docker.com/get-docker/")
	}
	if err := exec.Command("docker", "info").Run(); err != nil {
		return errors.New("Docker is installed but not running: start Docker Desktop (or `colima start`) and retry")
	}
	if err := exec.Command("docker", "compose", "version").Run(); err != nil {
		return errors.New("Docker Compose v2 (`docker compose`) is required: update Docker or install the compose plugin")
	}
	return nil
}
