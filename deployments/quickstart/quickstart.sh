#!/bin/sh
# quickstart.sh: run Conduit locally with one command. Needs only Docker.
#
#   quickstart.sh          start (or restart) the stack and print how to use it
#   quickstart.sh status   show the services and your login again
#   quickstart.sh down     stop the stack, keeping its data and credentials
#   quickstart.sh reset    stop and delete all data and credentials
#
# Environment:
#   CONDUIT_UI_PORT        UI port on 127.0.0.1 (default 8080)
#   CONDUIT_GATEWAY_PORT   gateway port on 127.0.0.1 (default 4317)
#   CONDUIT_VERSION        image tag (default v0.1.0)
#   CONDUIT_DEMO_AGENT=0   don't start the simulated demo-agent
set -eu

DIR=$(cd "$(dirname "$0")" && pwd)
ROOT=$(cd "$DIR/../.." && pwd)
UI_PORT=${CONDUIT_UI_PORT:-8080}
GATEWAY_PORT=${CONDUIT_GATEWAY_PORT:-4317}
FIRST_TRACE_TIMEOUT=${CONDUIT_FIRST_TRACE_TIMEOUT:-90}

if [ -t 1 ] && [ -z "${NO_COLOR:-}" ]; then
  B=$(printf '\033[1m'); R=$(printf '\033[31m'); G=$(printf '\033[32m'); D=$(printf '\033[2m'); X=$(printf '\033[0m')
else
  B=; R=; G=; D=; X=
fi
say()  { printf '%s==>%s %s\n' "$B" "$X" "$*"; }
die()  { printf '%serror:%s %s\n' "$R" "$X" "$*" >&2; exit 1; }

compose() { docker compose --project-directory "$DIR" -f "$DIR/compose.yml" "$@"; }

preflight() {
  command -v docker >/dev/null 2>&1 || die "Docker is not installed. Get it from https://docs.docker.com/get-docker/"
  docker info >/dev/null 2>&1 || die "Docker is installed but not running. Start Docker Desktop (or 'colima start') and rerun."
  docker compose version >/dev/null 2>&1 || die "Docker Compose v2 is required ('docker compose'). Update Docker, or install the compose plugin."
}

random_hex() { od -An -tx1 -N"$1" /dev/urandom | tr -d ' \n'; }

# .env holds generated secrets and settings for compose; it is gitignored.
write_env() {
  [ -f "$DIR/.env" ] && return
  umask 077
  cat >"$DIR/.env" <<EOF
# Generated by quickstart.sh. Delete with 'quickstart.sh reset'.
CLICKHOUSE_PASSWORD=$(random_hex 24)
UI_SESSION_KEY=$(random_hex 32)
EOF
}

first_trace_seen() {
  # shellcheck disable=SC2016 # expanded inside the container
  compose exec -T clickhouse sh -c 'clickhouse-client --user obs --password "$CLICKHOUSE_PASSWORD" --database observability -q "SELECT count() FROM spans WHERE agent_name = '"'"'demo-agent'"'"'"' 2>/dev/null </dev/null | grep -qv '^0$'
}

banner() {
  login=$(cat "$DIR/.conduit/ui-login.txt" 2>/dev/null || echo "? (missing: run 'quickstart.sh reset')")
  user=${login%% *}; pass=${login#* }
  certs="$DIR/.conduit/certs"
  cat <<EOF

${G}${B}Conduit is running.${X}

  ${B}UI${X}        http://localhost:$UI_PORT
  ${B}Login${X}     $user / $pass
  ${B}Gateway${X}   localhost:$GATEWAY_PORT (mTLS)

${B}Send a trace from code${X} (as agent "my-agent"; the examples find the certificates):

  Go:      cd "$ROOT/examples/go" && go run ./hello-trace
  Python:  pip install -e "$ROOT/sdk/python" && python "$ROOT/examples/python/hello_trace.py"
  More:    tool calling, asyncio, Claude, OpenAI: $ROOT/examples/README.md
  Certs:   $certs ${D}(for your own agent)${X}

Docs: https://tjscanlan.github.io/conduit/   Stop: $0 down
EOF
}

up() {
  preflight
  start=$(date +%s)
  write_env
  mkdir -p "$DIR/.conduit"
  # conduit-init runs as you, so the generated agent keys are yours to use.
  CONDUIT_UID=$(id -u) CONDUIT_GID=$(id -g)
  export CONDUIT_UID CONDUIT_GID

  scale=
  [ "${CONDUIT_DEMO_AGENT:-1}" = 0 ] && scale="--scale demo-agent=0"
  say "Starting Conduit ${CONDUIT_VERSION:-v0.1.0} (first run pulls images and builds two small ones; later runs are fast)"
  # shellcheck disable=SC2086 # $scale is intentionally split
  if ! compose up -d --wait --wait-timeout 300 $scale; then
    printf '\n' >&2
    compose ps -a >&2 || true
    die "the stack did not become healthy. Common causes:
  - port $UI_PORT or $GATEWAY_PORT is in use: rerun with CONDUIT_UI_PORT=18080 CONDUIT_GATEWAY_PORT=14317
  - Docker has too little memory: give it at least 2 GiB
Logs: docker compose -f $DIR/compose.yml logs"
  fi
  say "Stack is healthy after $(( $(date +%s) - start ))s"

  if [ "${CONDUIT_DEMO_AGENT:-1}" != 0 ]; then
    first_trace_seen || say "Waiting for demo-agent's first trace"
    i=0
    until first_trace_seen; do
      i=$((i + 1))
      [ "$i" -ge "$FIRST_TRACE_TIMEOUT" ] && die "no trace from demo-agent after ${FIRST_TRACE_TIMEOUT}s. Check: docker compose -f $DIR/compose.yml logs demo-agent gateway collector"
      sleep 1
    done
    say "Traces from demo-agent are arriving ($(( $(date +%s) - start ))s after start)"
  fi
  banner
}

case "${1:-up}" in
  up)     up ;;
  status) preflight; compose ps; banner ;;
  down)   preflight; compose down; say "Stopped. Data and credentials are kept; '$0' starts it again." ;;
  reset)
    preflight
    compose down -v --remove-orphans
    rm -rf "${DIR:?}/.conduit" "${DIR:?}/.env"
    say "Deleted all quickstart data and credentials." ;;
  -h|--help|help) sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//' ;;
  *) die "unknown command '$1' (try: up, status, down, reset)" ;;
esac
